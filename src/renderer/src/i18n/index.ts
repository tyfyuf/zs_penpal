const dictionaries: Record<Locale, Record<string, string>> = { zh, en }

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  let s = dictionaries[locale][key] ?? dictionaries.zh[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v))
    }
  }
  return s
}

interface I18nStore {
  locale: Locale
  setLocale(l: Locale): void
}

export const useI18nStore = create<I18nStore>((set) => ({
  locale: (localStorage.getItem('ui-locale') as Locale) ?? 'zh',
  setLocale(l) {
    localStorage.setItem('ui-locale', l)
    set({ locale: l })
  }
}))

/** 组件内使用：const t = useT() */
export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const locale = useI18nStore((s) => s.locale)
  return (key, vars) => translate(locale, key, vars)
}

/** 非组件上下文（toast 等）使用 */
export function tGlobal(key: string, vars?: Record<string, string | number>): string {
  return translate(useI18nStore.getState().locale, key, vars)
}
